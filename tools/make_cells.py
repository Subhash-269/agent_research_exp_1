#!/usr/bin/env python3
"""Generate one .sbatch per (target, method) cell of the sweep.

Runs on the laptop. The generated files are committed, so what ran is readable
in the history rather than reconstructed from a loop (R8: author here, transfer
it). Each one is thin: it sets the cell's variables and sources
tools/cell_worker.sh, which holds the logic and is pushed to the cluster once.

Every constant carries its source (R1).
"""
from __future__ import annotations

from pathlib import Path

HERE = Path(__file__).resolve().parent
JOBS = HERE.parent / "jobs"

# --- the matched allowance -------------------------------------------------
# source: chosen by me, no external source. Every cell gets the same walltime,
# which is what PROJECT.md means by matching methods on GPU-hours rather than
# on sample count.
WALLTIME = "02:00:00"
WALL_SECONDS = 2 * 3600

# source: chosen by me, no external source. The run date, so a seed is legible
# as belonging to this run.
SEED_BASE = 20261105

# source: measured, `scontrol show job` on the 11646330-11646416 batch.
# This was gpu:h200:1 and it did NOT take effect: connector.py submit puts
# --gres on the sbatch command line from its config (runners/hpc.py:143), which
# overrides the #SBATCH directive, and every one of those eight jobs was
# allocated gpu:a100:1. Rather than keep a directive that the submit path
# ignores, the cells now name the card they actually get, and the submit passes
# the same value explicitly so the two agree. A100-SXM4-40GB is compute
# capability 8.0 with bf16, which is what S3 requires and what the model needs.
GRES = "gpu:a100:1"
PARTITION = "gpu"

# --- targets ---------------------------------------------------------------
# source: configs/targets/targets_dict.yaml, chain counts read from the shipped
# PDBs in job 11638131.
TARGETS = [
    # (tag, task_name, n_chains)
    ("tnf",  "38_TNFalpha", 3),   # multi-chain, S10's case, exercised first
    ("trka", "33_TrkA",     1),   # single-chain control, same binder length range
]

# --- methods ---------------------------------------------------------------
# nsamples is NOT a matched quantity. It is set per method so the cell roughly
# fills its walltime allowance, using the only throughput measurement this run
# has: job 11638953 on 38_TNFalpha / best-of-n / H200 measured 75.2 s per
# sample to generate and 104.8 s per sample to evaluate (1 native + 8 MPNN
# sequences folded), on top of about 400 s of fixed model and parameter load.
#
#   best-of-n: (7200 - 400) / 180 = 37.8 samples would fill the allowance;
#              32 is taken, leaving headroom for a slower target.
#
# The three search methods and the refinement path have NO measurement yet:
# one beam-search update folds beam_width x n_branch = 16 candidates per
# checkpoint, across 5 checkpoints, so a single design costs far more than an
# independent draw. Their nsamples is set low on purpose. Whatever they
# complete inside the same allowance is the measurement, and if a cell
# completes fewer designs than another, that IS the comparison PROJECT.md asks
# for rather than a flaw in it.
METHODS = [
    # (tag, search.algorithm, nsamples, extra hydra overrides)
    # 32 -> 16. source: measured, job 11646330. At nsamples=32 generation
    # died with torch.OutOfMemoryError on an A100-40GB, and the fix for THAT
    # is batch_size=2 in cell_worker.sh, not a smaller nsamples. nsamples
    # comes down for a separate reason: the 32 was sized from H200 throughput
    # (job 11638953) and this run has no A100 throughput measurement at all.
    # 16 x 180 s + 400 s = 3280 s against a 7200 s allowance leaves room for
    # an A100 to be more than twice as slow as the H200 the number came from.
    # If it turns out faster, the cell finishes early and the next job extends
    # the curve; if it overruns, the walltime guard skips evaluation with a
    # reason rather than letting Slurm kill the job mid-generation.
    ("bon",  "best-of-n",   16, ""),
    ("beam", "beam-search",  4, ""),
    ("fk",   "fk-steering",  4, ""),
    ("mcts", "mcts",         4, ""),
    # PROJECT.md method 5. Reported everywhere as "Generate and Hallucinate,
    # repo-internal variant": it refines with the model repository's own
    # refinement.algorithm, NOT with a hallucination baseline's optimiser,
    # because those baselines are deferred. Its curve is not comparable to one
    # produced with a baseline refiner and must not be presented as if it were.
    ("gh",   "best-of-n",    4,
     "++refinement.algorithm=sequence_hallucination"),
]

TEMPLATE = """#!/bin/bash
# =============================================================================
# Sweep cell: target {task_name} ({n_chains} chain{plural}) x method {method_label}
#
# Generated by tools/make_cells.py. The logic lives in tools/cell_worker.sh,
# which is pushed to $RUN_ROOT/tools/ once; this file only declares the cell.
#
# Allowance: {walltime} on one {gres}. Identical for every cell, which is how
# the methods are matched on GPU-hours rather than on sample count.
# =============================================================================
#SBATCH --job-name=cxa_{cell_tag}
#SBATCH --partition={partition}
#SBATCH --gres={gres}
#SBATCH --cpus-per-task=12
#SBATCH --mem=96G
#SBATCH --time={walltime}

# S15: an explicit seed, distinct per cell, recorded with every design and
# score this job emits. seed = {seed_base} + {cell_index} = {seed}
export TARGET="{task_name}"
export METHOD="{algorithm}"
export SEED={seed}
export NSAMPLES={nsamples}
export CELL_TAG="{cell_tag}"
export EXTRA_OVERRIDES="{extra}"

source "/scratch/$USER/complexa_armB_20261105/tools/cell_worker.sh"
"""


def main() -> int:
    JOBS.mkdir(exist_ok=True)
    written = []
    cell_index = 0
    for t_tag, task_name, n_chains in TARGETS:
        for m_tag, algorithm, nsamples, extra in METHODS:
            cell_index += 1
            cell_tag = f"{t_tag}_{m_tag}"
            method_label = (
                "Generate and Hallucinate, repo-internal variant"
                if m_tag == "gh" else algorithm
            )
            text = TEMPLATE.format(
                task_name=task_name, n_chains=n_chains,
                plural="" if n_chains == 1 else "s",
                method_label=method_label, algorithm=algorithm,
                nsamples=nsamples, extra=extra, cell_tag=cell_tag,
                seed=SEED_BASE + cell_index, seed_base=SEED_BASE,
                cell_index=cell_index, walltime=WALLTIME,
                gres=GRES, partition=PARTITION,
            )
            p = JOBS / f"cell_{cell_tag}.sbatch"
            p.write_text(text, encoding="utf-8", newline="\n")
            written.append((cell_tag, task_name, algorithm, nsamples,
                            SEED_BASE + cell_index))

    print(f"{len(written)} cells written to {JOBS}")
    print(f"{'cell':<12} {'target':<14} {'algorithm':<13} {'nsamples':>8} {'seed':>10}")
    for row in written:
        print(f"{row[0]:<12} {row[1]:<14} {row[2]:<13} {row[3]:>8} {row[4]:>10}")
    total_h = len(written) * WALL_SECONDS / 3600
    print(f"\nallowance: {len(written)} cells x {WALL_SECONDS} s x 1 GPU / 3600 "
          f"= {total_h:.1f} GPU-hours if every cell runs its full walltime")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
